export function fmtMoney(val, currency = Store.settings.currency || 'FCFA') {
  const n = Math.round(Number(val) || 0);
  return `${n.toLocaleString('fr-FR')} ${currency}`;
}

export function fmtDate(str) {
  if (!str) return '—';
  const d = new Date(str.replace(' ', 'T'));
  if (Number.isNaN(d.getTime())) return str;
  return d.toLocaleString('fr-FR', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });
}

export function fmtShortDate(str) {
  if (!str) return '—';
  const d = new Date(str.length === 10 ? str + 'T00:00:00' : str.replace(' ', 'T'));
  if (Number.isNaN(d.getTime())) return str;
  return d.toLocaleDateString('fr-FR', { day: '2-digit', month: '2-digit', year: 'numeric' });
}

export function esc(val) {
  return String(val ?? '').replace(/[&<>"']/g, (ch) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;',
  }[ch]));
}

export function toast(message, type = 'info') {
  const root = document.getElementById('toast-root');
  if (!root) return;
  const el = document.createElement('div');
  el.className = `toast ${type}`;
  el.innerHTML = `<span>${esc(message)}</span>`;
  root.appendChild(el);
  setTimeout(() => {
    el.style.opacity = '0';
    setTimeout(() => el.remove(), 220);
  }, 3400);
}

export async function api(path, options = {}) {
  const { method = 'GET', body } = options;
  const res = await fetch('/api/' + path.replace(/^\/?api\//, ''), {
    method,
    credentials: 'same-origin',
    headers: { 'Content-Type': 'application/json' },
    body: body !== undefined ? JSON.stringify(body) : undefined,
  });
  const data = await res.json().catch(() => ({}));
  if (res.status === 401 && !path.startsWith('auth/')) {
    Store.user = null;
    window.dispatchEvent(new CustomEvent('fincaisse:unauthorized'));
  }
  if (!res.ok || data.ok === false) {
    throw new Error(data.error || `Erreur serveur (${res.status})`);
  }
  return data;
}

export function openModal({ title, bodyHtml, footerHtml = '', large = false, onMount }) {
  const existing = document.getElementById('fc-active-modal');
  if (existing) existing.remove();

  const dlg = document.createElement('dialog');
  dlg.id = 'fc-active-modal';
  dlg.className = `modal ${large ? 'modal-lg' : ''}`;
  dlg.innerHTML = `
    <div class="modal-head">
      <h3>${esc(title)}</h3>
      <button type="button" class="btn btn-ghost btn-sm" data-close aria-label="Fermer">✕</button>
    </div>
    <div class="modal-body">${bodyHtml}</div>
    ${footerHtml ? `<div class="modal-foot">${footerHtml}</div>` : ''}
  `;
  document.body.appendChild(dlg);

  const close = () => {
    dlg.close();
    dlg.remove();
  };

  dlg.querySelectorAll('[data-close]').forEach((btn) => btn.addEventListener('click', close));
  dlg.addEventListener('click', (e) => {
    if (e.target === dlg) close();
  });

  dlg.showModal();
  if (onMount) onMount(dlg, close);
  return { dlg, close };
}

